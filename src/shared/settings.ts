/** Numeric settings and their allowed range; the options page and mergeSettings both clamp to it. */
export const RANGES = {
  "limits.tabs": [1, 20],
  "limits.bookmarks": [1, 20],
  "limits.history": [1, 20],
  "limits.suggestions": [1, 10],
  "switcher.maxCards": [2, 8],
  "appearance.width": [520, 1000],
  "appearance.radius": [0, 24],
} as const;

/**
 * Deep-merges saved values over defaults. Unknown keys and values of the wrong type are dropped,
 * so old or hand-edited data can never break the extension.
 */
export function mergeSettings(saved: unknown): Settings {
  const merged = mergeInto(DEFAULT_SETTINGS, saved);
  // Before 3.1 overflow was the boolean switcher.softWrap.
  const old = isObject(saved) && isObject(saved.switcher) ? saved.switcher : null;
  if (old && old.overflow === undefined && old.softWrap === true) merged.switcher.overflow = "wrap";
  if (!["fit", "scroll", "wrap"].includes(merged.switcher.overflow)) merged.switcher.overflow = DEFAULT_SETTINGS.switcher.overflow;
  // Hand-edited or imported numbers outside the UI's range would break layouts.
  for (const [path, [min, max]] of Object.entries(RANGES)) {
    const [group, key] = path.split(".") as [keyof Settings, string];
    const target = merged[group] as Record<string, number>;
    target[key] = Math.min(Math.max(Math.round(target[key]), min), max);
  }
  return merged;
}

function mergeInto<T>(base: T, patch: unknown): T {
  if (!isObject(patch)) return structuredClone(base);
  const out = {} as T;
  for (const key of Object.keys(base as object) as (keyof T)[]) {
    const b = base[key];
    const p = patch[key as string];
    if (isObject(b)) out[key] = mergeInto(b, p);
    else out[key] = p === undefined || typeof p !== typeof b ? b : (p as T[keyof T]);
  }
  return out;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === "object" && !Array.isArray(value);
}

// ---------- export / import ----------

export interface SettingsFile {
  app: "cmdly";
  version: 1;
  exportedAt: string;
  settings: Settings;
}

export function toExportFile(settings: Settings): SettingsFile {
  return { app: "cmdly", version: 1, exportedAt: new Date().toISOString(), settings: mergeSettings(settings) };
}

/** Parses an export file (or a bare settings object). Throws a user-readable Error on bad input. */
export function fromImportFile(data: unknown): Settings {
  if (!isObject(data)) throw new Error(t("importNotCmdly"));
  if (data.app !== undefined && data.app !== "cmdly") throw new Error(t("importOtherApp"));
  const settings = data.app === "cmdly" ? data.settings : data;
  if (!isObject(settings)) throw new Error(t("importNoSettings"));
  if (!Object.keys(DEFAULT_SETTINGS).some((key) => key in settings)) {
    throw new Error(t("importNothingFound"));
  }
  return mergeSettings(settings);
}
