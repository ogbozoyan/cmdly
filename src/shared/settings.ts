/** What "keep window open" protects: nothing, the last remaining window, or every window. */
export type KeepOpenMode = "off" | "last" | "every";

/** More recent tabs than fit on one line: show only what fits, scroll sideways, or wrap into rows. */
export type SwitcherOverflow = "fit" | "scroll" | "wrap";

/** User settings. Stored in chrome.storage.sync, so they follow the user across devices. */
export interface Settings {
  /** Keyboard shortcuts in Shortcut format (see shortcuts.ts). Empty string = disabled. */
  shortcuts: {
    openBar: string;
    copyUrl: string;
    undoClose: string;
  };
  features: {
    /** Show the bar over the current page instead of a separate tab. */
    overlay: boolean;
    commands: boolean;
    calculator: boolean;
    uuid: boolean;
    encode: boolean;
    jwt: boolean;
    /** JSON / YAML viewer, formatter and converter. */
    formats: boolean;
    /** HTML / Markdown / OpenAPI preview of pasted text. */
    markup: boolean;
    /** Let the preview load images, fonts and styles from the network (off: nothing is requested). */
    markupRemote: boolean;
    /** Every chrome://settings section as a command (background/chrome-pages.ts). */
    chromeSettings: boolean;
  };
  bar: {
    /** Keep the typed text when the bar closes or its page reloads, until something is run. */
    restoreDraft: boolean;
    /** An open bar comes back after its page reloads (same address only). */
    reopenAfterReload: boolean;
  };
  windows: {
    /** Closing the last tab doesn't close the window (see background/keep-open-plan.ts). */
    keepOpen: KeepOpenMode;
  };
  switcher: {
    /** Remember a small screenshot of each tab to show in the tab switcher (kept in memory only). */
    thumbnails: boolean;
    /** Take over Chrome's Ctrl+Tab / Ctrl+Shift+Tab (the neighbour tab flashes for a moment). */
    ctrlTab: boolean;
    /** What happens to cards that don't fit on one line (see SwitcherOverflow). */
    overflow: SwitcherOverflow;
    /** Most cards shown when overflow = "fit" (also capped by the window width). */
    maxCards: number;
  };
  tools: {
    /** Version generated by "uuid"; Tab on the UUID row cycles and saves it. */
    uuidVersion: "v4" | "v7" | "v1";
  };
  sources: {
    tabs: boolean;
    bookmarks: boolean;
    history: boolean;
    /** Ask the search engine for suggestions while typing (sends the typed text to it). */
    suggestions: boolean;
  };
  /** Engine asked for suggestions; the search itself always uses Chrome's default engine. */
  suggest: {
    engine: SuggestEngine;
    /** Suggestions arrive late: at the bottom they never push the user's own tabs and history down. */
    position: "bottom" | "top";
  };
  /** Opt-in features that may change or go away (Settings → Experimental). */
  experimental: {
    /** One relevance scale for every source, word-start matching, a top hit that owns Enter (shared/ranking.ts). */
    ranking: boolean;
    /** Remember which row was picked for a query, locally, to rank it higher next time (shared/learned.ts). */
    learned: boolean;
    /** ">" lists every command, "settings" every Chrome settings page. */
    scopes: boolean;
  };
  limits: {
    tabs: number;
    bookmarks: number;
    history: number;
    suggestions: number;
  };
  appearance: {
    /** UI language: "auto" follows Chrome, otherwise a src/i18n locale (en, ru, zh_CN, de, fr). */
    language: string;
    theme: "dark" | "light" | "system";
    accent: string;
    position: "center" | "top";
    width: number;
    /** Corner radius of the bar, px. */
    radius: number;
  };
}

