/** What "keep window open" protects: nothing, the last remaining window, or every window. */
export type KeepOpenMode = "off" | "last" | "every";

/** User settings. Stored in chrome.storage.sync, so they follow the user across devices. */
export interface Settings {
  /** Keyboard shortcuts in Shortcut format (see shortcuts.ts). Empty string = disabled. */
  shortcuts: {
    openBar: string;
    copyUrl: string;
    undoClose: string;
  };
  features: {
    /** Show the bar over the current page instead of a separate tab. */
    overlay: boolean;
    commands: boolean;
    calculator: boolean;
    uuid: boolean;
    encode: boolean;
    jwt: boolean;
    /** JSON / YAML viewer, formatter and converter. */
    formats: boolean;
    /** HTML / Markdown / OpenAPI preview of pasted text. */
    markup: boolean;
    /** Let the preview load images, fonts and styles from the network (off: nothing is requested). */
    markupRemote: boolean;
  };
  windows: {
    /** Closing the last tab doesn't close the window (see background/keep-open-plan.ts). */
    keepOpen: KeepOpenMode;
  };
  switcher: {
    /** Remember a small screenshot of each tab to show in the tab switcher (kept in memory only). */
    thumbnails: boolean;
    /** Take over Chrome's Ctrl+Tab / Ctrl+Shift+Tab (the neighbour tab flashes for a moment). */
    ctrlTab: boolean;
    /** Wrap cards into rows instead of one horizontally scrolling line. */
    softWrap: boolean;
  };
  tools: {
    /** Version generated by "uuid"; Tab on the UUID row cycles and saves it. */
    uuidVersion: "v4" | "v7" | "v1";
  };
  sources: {
    tabs: boolean;
    bookmarks: boolean;
    history: boolean;
    /** Ask the search engine for suggestions while typing (sends the typed text to it). */
    suggestions: boolean;
  };
  /** Engine asked for suggestions; the search itself always uses Chrome's default engine. */
  suggest: {
    engine: SuggestEngine;
  };
  limits: {
    tabs: number;
    bookmarks: number;
    history: number;
    suggestions: number;
  };
  appearance: {
    /** UI language: "auto" follows Chrome, otherwise a src/i18n locale (en, ru, zh_CN, de, fr). */
    language: string;
    theme: "dark" | "light" | "system";
    accent: string;
    position: "center" | "top";
    width: number;
  };
}

